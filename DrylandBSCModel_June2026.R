WC_scale_moss    <- {
  wc  <- seq(0, 1, 0.01)
  raw <- low_water_response_fxn(WC=wc, WC_k=WC_k_moss, Pgmax=1) *
    high_water_response_fxn(WC=wc, slope=slope_moss, intercept=intercept_moss, Pgmax=1)
  max(raw)
}


